namespace
{
    constexpr bool EncryptCache          = !DebugMode();
    constexpr const char* CacheExtension = EncryptCache ? "dbe" : "db";

    constexpr std::string_view CredentialAttribute_sv = "CSPro_csweb_cache";
    constexpr size_t CredentialHashLength             = 8; // used as 16 hex characters

    constexpr size_t CachePasswordHashLength = 128;
}


CSWebRepositoryCache::CSWebRepositoryCache(CSWebRepository& repository, const CSWebRepositoryCacheCredential& credential,
                                           const JsonNode& dictionary_metadata_json_node)
    :   m_repository(repository)
{
    constexpr int open_flags = Sqlite::OpenFlags::ReadWrite | Sqlite::OpenFlags::Create;

    if( credential.cache_password.has_value() )
    {
        m_db.OpenEncrypted(credential.cache_file_path, *credential.cache_password, open_flags);
    }

    else
    {
        m_db.Open(credential.cache_file_path, open_flags);
    }

    Initialize(dictionary_metadata_json_node);
}


CSWebRepositoryCache::~CSWebRepositoryCache()
{
}


std::unique_ptr<CSWebRepositoryCache> CSWebRepositoryCache::Create(CSWebRepository& repository, const DeviceId& server_device_id,
                                                                   const CSWebUser& user, const JsonNode& dictionary_metadata_json_node)
{
    const std::string& dictionary_name = repository.m_syncableDictionaryName;

    // see if there already is a cache created for this user
    CredentialStore credential_store;
    std::vector<CSWebRepositoryCacheCredential> credentials;

    try
    {
        const JsonNode json_node = credential_store.RetrieveFromJson<JsonNode>(CredentialAttribute_sv);
        credentials = json_node.GetArray().GetVector<CSWebRepositoryCacheCredential>();

        const auto& lookup = std::find_if(credentials.crbegin(), credentials.crend(),
            [&](const CSWebRepositoryCacheCredential& credential)
            {
                return ( server_device_id == credential.server_device_id &&
                         user == credential.user &&
                         dictionary_name == credential.dictionary_name &&
                         EncryptCache == credential.cache_password.has_value() );
            });

        if( lookup != credentials.crend() )
            return std::unique_ptr<CSWebRepositoryCache>(new CSWebRepositoryCache(repository, *lookup, dictionary_metadata_json_node));
    }

    catch(...)
    {
        // errors are ignored in favor of creating a new cache
        ASSERT(credential_store.Retrieve(CredentialAttribute_sv).empty());
    }

    // if here, we will create a new cache file in %AppData%/CSPro/csweb_cache/[dictionary_name]/
    ASSERT(dictionary_name == Path::CreateValidFilename(dictionary_name));

    const std::string cache_directory = Path::Combine(GetAppDataPath(), "csweb_cache", dictionary_name);
    std::string cache_file_path = PortableFunctions::GetUniqueFilePathInDirectory(cache_directory, CacheExtension);
    FileIO::CreateDirectoriesForFile(cache_file_path);

    // when used, the file password will be randomly generated by hashing some values together and using
    // the dictionary name as a salt;
    // CRYPT_TODO: if added to CSPro at some point, modify this to use a key derivation scheme
    std::optional<std::vector<std::byte>> cache_password;

    if constexpr(EncryptCache)
    {
        const std::string values_for_password_hash = SO::Concatenate(user.id, user.role_name, DoubleToString(GetTimestamp()));

        cache_password.emplace(Hash::Hash(
            reinterpret_cast<const std::byte*>(values_for_password_hash.data()),
            values_for_password_hash.length(),
            reinterpret_cast<const std::byte*>(dictionary_name.data()),
            dictionary_name.length(),
            CachePasswordHashLength
        ));
    }

    CSWebRepositoryCacheCredential credential
    {
        server_device_id,
        user,
        dictionary_name,
        std::move(cache_file_path),
        std::move(cache_password)
    };

    auto cache = std::unique_ptr<CSWebRepositoryCache>(new CSWebRepositoryCache(repository, credential, dictionary_metadata_json_node));

    // on success, store the new credential
    credentials.emplace_back(std::move(credential));
    credential_store.StoreAsJson(CredentialAttribute_sv, credentials);

    return cache;
}


void CSWebRepositoryCache::Initialize(const JsonNode& dictionary_metadata_json_node)
{
    ASSERT(m_repository.m_caseAccess != nullptr);
    ASSERT(!m_currentServerRevision.has_value());

    // get details on the server's current max revision
    m_currentServerRevision = dictionary_metadata_json_node.GetOptional<int64_t>(JK::maxRevision);

    // all serializers will be created using full case access
    m_caseAccess = CaseAccess::CreateAndInitializeFullCaseAccess(m_repository.m_caseAccess->GetDataDict());
    m_case = m_caseAccess->CreateCase();
    m_syncCaseJsonSerializer = std::make_unique<SyncCaseV3JsonSerializer>(m_caseAccess);

    // create the cache tables and indices if necessary
    if( !m_db.TableExists("cases") )
    {
        m_db.Execute(
            "CREATE TABLE `cases` ("
            "`id` INTEGER NOT NULL,"
            "`uuid` TEXT NOT NULL,"
            "`key` TEXT NOT NULL,"
            "`deleted` INTEGER NOT NULL,"
            "`server_revision` INTEGER NOT NULL,"
            "`data_revision` INTEGER NOT NULL,"
            "`data_type` INTEGER NOT NULL,"
            "`data` TEXT NOT NULL,"
            "PRIMARY KEY(`id`)"
            ");"
        );

        m_db.Execute(
            "CREATE INDEX `cases-key` "
            "ON `cases` (`key`)"
        );
    }

    // speed up access to the database by disabling journaling and synchronous writes
    m_db.Execute(Sqlite::Commands::SetJournalModeToOff);
    m_db.Execute(Sqlite::Commands::SetSynchronousOff);
}


void CSWebRepositoryCache::DeleteCache(std::unique_ptr<CSWebRepositoryCache>& cache) noexcept
{
    if( cache == nullptr )
        return;

    try
    {
        const std::string cache_file_path = cache->m_db.GetFilePath();
        cache.reset();
        PortableFunctions::FileDeleteWithExceptions(cache_file_path);
    }
    catch(...) { ASSERT(false); }
}


void CSWebRepositoryCache::CacheCase(const JsonNode& case_json_node, const JsonNode& metadata_json_node) noexcept
{
    if( !m_currentServerRevision.has_value() )
        return;

    try
    {
        CSWebRepository::ParseJsonCase(*m_case, case_json_node, metadata_json_node, *m_syncCaseJsonSerializer);

        const std::unique_ptr<JsonStringWriter> case_data_json_writer = Json::CreateStringWriter(JsonFormattingOptions::Compact);
        m_syncCaseJsonSerializer->WriteCase(*case_data_json_writer, *m_case);
        const std::string parsed_case_json = case_data_json_writer->ReleaseString();

        m_db.PrepareOrResetStatement(m_stmtWriteCase,
            "INSERT OR REPLACE INTO `cases` "
            "(`id`, `uuid`, `key`, `deleted`, `server_revision`, `data_revision`, `data_type`, `data`) "
            "VALUES(?,?,?,?,?,?,?,?);"
        );

        ASSERT(static_cast<int64_t>(m_case->GetPositionInRepository()) == metadata_json_node.Get<int64_t>(JK::position));
        ASSERT(static_cast<int64_t>(m_case->GetPositionInRepository()) == m_case->GetPositionInRepository());

        m_stmtWriteCase.Bind(1, static_cast<int64_t>(m_case->GetPositionInRepository()))
                       .Bind(2, m_case->GetUuid())
                       .Bind(3, m_case->GetKey())
                       .Bind(4, m_case->GetDeleted())
                       .Bind(5, *m_currentServerRevision)
                       .Bind(6, metadata_json_node.Get<int64_t>(JK::revision))
                       .Bind(7, static_cast<int>(DataType::Case))
                       .Bind(8, parsed_case_json);

        if( m_stmtWriteCase.Step() != Sqlite::Result::Done )
            throw ProgrammingErrorException();
    }
    catch(...) { ASSERT(false); }
}


bool CSWebRepositoryCache::ReadCaseByKey(Case& data_case, const std::string& key) noexcept
{
    if( !m_currentServerRevision.has_value() )
        return false;

    try
    {
        m_db.PrepareOrResetStatement(m_stmtQueryCasesByKey,
            "SELECT `id`, `data` "
            "FROM `cases` "
            "WHERE `key` = ? AND `deleted` = 0 AND `server_revision` >= ? AND `data_type` >= ? "
            "LIMIT 1;"
        );

        m_stmtQueryCasesByKey.Bind(1, key)
                             .Bind(2, *m_currentServerRevision)
                             .Bind(3, static_cast<int>(DataType::Case));

        if( m_stmtQueryCasesByKey.Step() == Sqlite::Result::Row )
        {
            const JsonNode& json_node = Json::Parse(m_stmtQueryCasesByKey.GetColumn<std::string>(1));
            data_case.ParseJson(json_node);

            data_case.SetPositionInRepository(m_stmtQueryCasesByKey.GetColumn<double>(0));

            return true;
        }
    }
    catch(...) { ASSERT(false); }

    return false;
}


bool CSWebRepositoryCache::ReadCaseByPosition(Case& data_case, const int64_t position) noexcept
{
    if( !m_currentServerRevision.has_value() )
        return false;

    try
    {
        m_db.PrepareOrResetStatement(m_stmtQueryCasesByPosition,
            "SELECT `data` "
            "FROM `cases` "
            "WHERE `id` = ? AND `server_revision` >= ? AND `data_type` >= ? "
            "LIMIT 1;"
        );

        m_stmtQueryCasesByPosition.Bind(1, position)
                                  .Bind(2, *m_currentServerRevision)
                                  .Bind(3, static_cast<int>(DataType::Case));

        if( m_stmtQueryCasesByPosition.Step() == Sqlite::Result::Row )
        {
            const JsonNode& json_node = Json::Parse(m_stmtQueryCasesByPosition.GetColumn<std::string>(0));
            data_case.ParseJson(json_node);

            return true;
        }
    }
    catch(...) { ASSERT(false); }

    return false;
}
