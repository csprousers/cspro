int wmain(const int argc, const wchar_t* const argv[])
{
    try
    {
        if( argc < 2 )
            throw CSProException("Specify the location of the CSPro code directory.");

        const std::string code_directory = MakeFullPath(GetWorkingDirectory(), TC::ToUtf8(argv[1]));
        const std::string zAction_directory = Path::Combine(code_directory, "zAction");
        const std::string zLogicO_directory = Path::Combine(code_directory, "zLogicO");
        const std::string html_directory_windows = Path::Combine(code_directory, "html");
        const std::string html_directory_android = Path::Combine(code_directory, R"!(CSEntryDroid\app\src\main\assets\html)!");
        const std::string definitions_file_path = Path::Combine(zAction_directory, "action-definitions.json");

        // read the definitions...
        std::vector<GF::Function> action_definitions =
            [&]()
            {
                const std::unique_ptr<JsonSpecFile::Reader> json_reader = JsonSpecFile::CreateReader(definitions_file_path);
                return json_reader->GetArray().GetVector<GF::Function>();
            }();

        // ...sort by action namespace and name
        std::sort(action_definitions.begin(), action_definitions.end(),
            [&](const GF::Function& gf1, const GF::Function& gf2)
            {
                const int namespace_comparison = SO::CompareNoCase(gf1.namespace_name, gf2.namespace_name);
                return ( namespace_comparison != 0 ) ? ( namespace_comparison < 0 ) :
                                                       ( SO::CompareNoCase(gf1.name, gf2.name) < 0 );
            });

        // ...and resave the actions
        {
            const std::unique_ptr<JsonStringWriter> json_writer = Json::CreateStringWriter(JsonFormattingOptions::PrettySpacing);
            json_writer->Write(action_definitions);

            std::string actions_json = json_writer->ReleaseString();
            ASSERT(actions_json.back() == ']');
            actions_json.push_back('\n');
            SO::ConvertTabsToSpacesAndTrimRightEachLine(actions_json);

            FileIO::WriteText(definitions_file_path, actions_json, false);
        }


        // create the ActionInfo object for each action, which will create the action hashes
        std::vector<ActionInfo> action_infos;

        for( const GF::Function& action_definition : action_definitions )
            action_infos.emplace_back(action_definition);

        // write the ActionInvoker::Action enum class with associated hash values to zLogicO/ActionInvoker.h
        ReplaceAutogeneratedRegion(Path::Combine(zLogicO_directory, "ActionInvoker.h"), { CreateActionEnumText(action_infos) });

        // write the function table and definitions to zLogicO/ActionInvoker.cpp
        ReplaceAutogeneratedRegion(Path::Combine(zLogicO_directory, "ActionInvoker.cpp"), { CreateFunctionTableText(action_infos),
                                                                                            CreateJsonFunctionDefinitionsText(action_infos) });

        // write the FunctionNamespace enum class to zLogicO/FunctionTable.h
        if( UpdateFunctionTableHeaderFile )
            ReplaceAutogeneratedRegion(Path::Combine(zLogicO_directory, "FunctionTable.h"), { CreateFunctionNamespaceEnumText(action_infos) });

        // write the FunctionNamespace details to zLogicO/FunctionTable.cpp
        ReplaceAutogeneratedRegion(Path::Combine(zLogicO_directory, "FunctionTable.cpp"), { CreateFunctionNamespaceDetailsText(action_infos) });

        // write the function declarations to zAction/ActionInvoker.h
        ReplaceAutogeneratedRegion(Path::Combine(zAction_directory, "ActionInvoker.h"), { CreateFunctionDeclarationsText(action_infos) });

        // write the functions to the function mapping in zAction/ActionFunctionMapping.cpp
        ReplaceAutogeneratedRegion(Path::Combine(zAction_directory, "ActionFunctionMapping.cpp"), { CreateFunctionMappingText(action_infos) });

        // create the JavaScript files for the Windows and Android environments
        CreateActionInvokerJavaScript(action_infos, Path::Combine(zAction_directory, "action-invoker-template.js"),
            {
                Path::Combine(html_directory_windows, "action-invoker.js"),
                Path::Combine(html_directory_android, "action-invoker.js"),
            });
    }

    catch( const CSProException& exception )
    {
        MessageBoxW(nullptr, TC::ToWide(exception.what()).c_str(), L"Action Invoker Definition Updater", MB_OK | MB_ICONEXCLAMATION);
    }
}



