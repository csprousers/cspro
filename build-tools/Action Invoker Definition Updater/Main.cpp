ActionInfo::ActionInfo(const GF::Function& action_definition)
    :   GF::Function(action_definition),
        hash(CalculateHash())
{
}


int ActionInfo::CalculateHash() const
{
    const std::string action_name = GetNamespaceAndName('.');

    const std::vector<std::byte> hash_data = Hash::Hash(reinterpret_cast<const std::byte*>(action_name.data()), action_name.length(),
                                                        reinterpret_cast<const std::byte*>(HashSalt_sv.data()), HashSalt_sv.length(),
                                                        HashLength, HashIterations);
    ASSERT(hash_data.size() == sizeof(HashType));
    static_assert(sizeof(HashType) < sizeof(int));

    const int calculated_hash = *reinterpret_cast<const HashType*>(hash_data.data());
    ASSERT(calculated_hash >= 0);

    return calculated_hash;
}


std::string ActionInfo::GetNamespaceAndName(const char separator) const
{
    if( namespace_name.empty() )
        return name;

    return namespace_name + separator + name;
}


std::string ActionInfo::GetActionEnumClassId(const bool name_only) const
{
    std::string id = GetActionInvokerMethodName();

    if( name_only )
        return id;

    return "ActionInvoker::Action::" + id;
}


std::string ActionInfo::GetFunctionNamespaceEnumClassId(const char separator) const
{
    if( namespace_name.empty() )
        return ActionInvokerBaseNamespace;

    return std::string(ActionInvokerBaseNamespace) + separator + namespace_name;
}


std::string ActionInfo::GetHelpFilename() const
{
    // modify some mappings:
    //     - UI.closeDialog -> UI.close
    //     - Logic.updateSymbolValue -> Logic.setSymbolValue
    const char* const name_to_use =
        ( namespace_name == "UI" && name == "closeDialog" )          ? "close" :
        ( namespace_name == "Logic" && name == "updateSymbolValue" ) ? "setSymbolValue" :
                                                                       name.c_str();

    return FormatText("%s_%s.html", GetFunctionNamespaceEnumClassId('_').c_str(), name_to_use);
}


std::string ActionInfo::GetActionInvokerMethodName() const
{
    return GetNamespaceAndName('_');
}



